# Writes tests/patterns_peepo.inc: every (Steps, Hits, Shift) Euclidelay
# allows, as Peepo's Euclidean module draws it. Run by hand on Linux (WSL on
# the PC) when Peepo's patterns change:
#
#   tools/gen_patterns.sh [PEEPO_DIR]       (default: /mnt/c/Pedal PI)
#
# Peepo's src/core/euclidean.hpp is GPL-3.0: it is read from Peepo's
# repository and compiled into a throwaway program here, never copied into
# Euclidelay. Only its output, the table, is kept.
set -eu

peepo=${1:-"/mnt/c/Pedal PI"}
header="$peepo/src/core/euclidean.hpp"
[ -f "$header" ] || { echo "gen_patterns: $header not found" >&2; exit 1; }
root=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

cat > "$work/gen.cpp" <<'EOF'
#include <cstdio>
#include "euclidean.hpp"
int main() {
    std::puts("// SPDX-License-Identifier: GPL-2.0-or-later");
    std::puts("// Generated by tools/gen_patterns.sh from Peepo's src/core/euclidean.hpp");
    std::puts("// (Peepo's output, not its code). Do not edit: run the script again.");
    std::puts("// {Steps, Hits, {mask for Shift 0 to 15}}; bit j of a mask is step j.");
    for (int steps = 1; steps <= 16; ++steps)
        for (int hits = 0; hits <= 16; ++hits) {
            std::printf("{%d, %d, {", steps, hits);
            for (int shift = 0; shift < 16; ++shift) {
                const auto p = peepo::euclidean_pattern(steps, hits, shift);
                unsigned mask = 0;
                for (int j = 0; j < steps; ++j)
                    if (p.at(j)) mask |= 1u << j;
                std::printf("%s0x%04x", shift ? ", " : "", mask);
            }
            std::puts("}},");
        }
}
EOF
${CXX:-c++} -std=c++17 -O1 -I "$peepo/src/core" "$work/gen.cpp" -o "$work/gen"
"$work/gen" > "$work/patterns_peepo.inc"
mv "$work/patterns_peepo.inc" "$root/tests/patterns_peepo.inc"
echo "wrote tests/patterns_peepo.inc ($(wc -l < "$root/tests/patterns_peepo.inc") lines)"
